import type { Hono } from "hono";
import { RESOURCE_CONFIG } from "../core/factory.js";

export interface OpenApiSpecOptions {
  title?: string;
  version?: string;
  description?: string;
  include?: string[];
}

const capitalize = (str: string) => str.charAt(0).toUpperCase() + str.slice(1);
const singularize = (str: string) => (str.endsWith("s") ? str.slice(0, -1) : str);

/**
 * Extracts JSON Schema properties from a Drizzle table definition.
 */
export function extractTableSchema(table: any): Record<string, any> {
  const properties: Record<string, any> = {};
  const required: string[] = [];

  if (!table || typeof table !== "object") {
    return { type: "object", properties: { id: { type: "integer" } } };
  }

  for (const [key, col] of Object.entries(table)) {
    if (key.startsWith("_")) continue;
    if (col && typeof col === "object" && ("dataType" in col || "columnType" in col || "name" in col)) {
      const colName = (col as any).name || key;
      const dataType = String((col as any).dataType || (col as any).columnType || "").toLowerCase();
      let propType = "string";
      let format: string | undefined;

      if (dataType.includes("int") || dataType.includes("serial") || dataType === "number") {
        propType = "integer";
      } else if (
        dataType.includes("real") ||
        dataType.includes("float") ||
        dataType.includes("double") ||
        dataType.includes("numeric")
      ) {
        propType = "number";
      } else if (dataType.includes("bool")) {
        propType = "boolean";
      } else if (dataType.includes("date") || dataType.includes("time")) {
        propType = "string";
        format = "date-time";
      } else if (dataType.includes("json")) {
        propType = "object";
      }

      properties[colName] = {
        type: propType,
        ...(format ? { format } : {}),
      };

      if ((col as any).notNull && !(col as any).hasDefault && !(col as any).isPrimaryKey) {
        required.push(colName);
      }
    }
  }

  return {
    type: "object",
    properties,
    ...(required.length > 0 ? { required } : {}),
  };
}

/**
 * Extracts JSON Schema from a validator (Zod or Standard Schema), falling back to table schema.
 */
export function extractValidatorSchema(validator: any, fallbackTable: any): Record<string, any> {
  if (validator && typeof validator.toJSONSchema === "function") {
    try {
      const res = validator.toJSONSchema();
      // Remove $schema keyword if present for OpenAPI compatibility
      const { $schema: _schema, ...clean } = res;
      return clean;
    } catch {
      // fallback
    }
  }

  return extractTableSchema(fallbackTable);
}

/**
 * Renders the HTML page for the interactive Scalar API Reference.
 * Loaded via official Scalar CDN web component with zero npm dependencies.
 */
export function renderScalarDocsHtml(specUrl: string, title = "API Documentation"): string {
  return `<!doctype html>
<html>
  <head>
    <title>${title}</title>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <style>
      body { margin: 0; padding: 0; }
    </style>
  </head>
  <body>
    <script id="api-reference" data-url="${specUrl}"></script>
    <script src="https://cdn.jsdelivr.net/npm/@scalar/api-reference"></script>
  </body>
</html>`;
}


/**
 * Generates an OpenAPI 3.1.0 specification object from defined HonoCube resources.
 */
export function generateOpenApiSpec(
  resources: Record<string, Hono<any>>,
  options: OpenApiSpecOptions = {}
): Record<string, any> {
  const title = options.title || "HonoCube API";
  const version = options.version || "2.0.2";
  const description = options.description || "Generated by HonoCube Enterprise Framework";

  const paths: Record<string, any> = {};
  const schemas: Record<string, any> = {
    ErrorEnvelope: {
      type: "object",
      properties: {
        success: { type: "boolean", example: false },
        error: {
          type: "object",
          properties: {
            code: { type: "string", example: "BAD_REQUEST" },
            message: { type: "string", example: "Invalid request" },
            details: { type: "object" },
          },
          required: ["code", "message"],
        },
      },
      required: ["success", "error"],
    },
    PaginationMeta: {
      type: "object",
      properties: {
        total: { type: "integer", example: 100 },
        limit: { type: "integer", example: 20 },
        page: { type: "integer", example: 1 },
        totalPages: { type: "integer", example: 5 },
        nextCursor: { type: "string", nullable: true },
        prevCursor: { type: "string", nullable: true },
        hasNext: { type: "boolean", example: true },
        hasPrev: { type: "boolean", example: false },
      },
      required: ["total", "limit"],
    },
  };

  for (const [resourcePath, resourceApp] of Object.entries(resources)) {
    if (options.include && !options.include.includes(resourcePath)) {
      continue;
    }

    const config = (resourceApp as any)[RESOURCE_CONFIG] || (resourceApp as any)["_honocube_config"];
    const resourceName = config?.name || resourcePath;
    const tag = resourceName;
    const modelName = capitalize(singularize(resourceName));
    const basePath = `/${resourcePath.replace(/^\/+/, "")}`;

    const tableSchema = extractTableSchema(config?.table);
    schemas[modelName] = tableSchema;

    // Resolve validator schemas for Create and Update
    let createSchema = tableSchema;
    let updateSchema = tableSchema;

    if (config?.validator) {
      if (typeof config.validator === "object" && "create" in config.validator) {
        createSchema = extractValidatorSchema(config.validator.create, config?.table);
        updateSchema = extractValidatorSchema(config.validator.update, config?.table);
      } else if (Array.isArray(config.validator)) {
        createSchema = extractValidatorSchema(config.validator[0], config?.table);
        updateSchema = extractValidatorSchema(config.validator[1] || config.validator[0], config?.table);
      } else {
        createSchema = extractValidatorSchema(config.validator, config?.table);
        updateSchema = createSchema;
      }
    }

    schemas[`${modelName}Create`] = createSchema;
    schemas[`${modelName}Update`] = updateSchema;

    const allowedMethods = new Set(
      config?.methods || [
        "list",
        "detail",
        "create",
        "update",
        "delete",
        "batch-update",
        "batch-delete",
        "aggregate",
      ]
    );

    const hasIdempotency = Boolean(config?.idempotency);
    const hasRateLimit = Boolean(config?.rateLimit);

    // Common response headers
    const rateLimitHeaders: Record<string, any> = hasRateLimit
      ? {
          "RateLimit-Limit": { schema: { type: "integer" }, description: "Quota limit per window" },
          "RateLimit-Remaining": { schema: { type: "integer" }, description: "Remaining quota in window" },
          "RateLimit-Reset": { schema: { type: "integer" }, description: "Seconds until window resets" },
        }
      : {};

    const idempotencyHeaderParam = hasIdempotency
      ? [
          {
            name: "Idempotency-Key",
            in: "header",
            required: false,
            schema: { type: "string" },
            description: "Unique idempotency key for safely retrying mutations",
          },
        ]
      : [];

    // 1. GET /resource (list)
    if (allowedMethods.has("list")) {
      const queryParams: any[] = [
        { name: "limit", in: "query", schema: { type: "integer" }, description: "Number of records to return" },
        { name: "sort", in: "query", schema: { type: "string" }, description: "Sort column name" },
        { name: "order", in: "query", schema: { type: "string", enum: ["asc", "desc"] }, description: "Sort direction" },
      ];

      const paginationType = config?.pagination?.type ?? "both";
      if (paginationType !== "cursor") {
        queryParams.push({ name: "page", in: "query", schema: { type: "integer" }, description: "Page number for offset pagination" });
      }
      if (paginationType !== "offset") {
        queryParams.push(
          { name: "cursor", in: "query", schema: { type: "string" }, description: "Opaque cursor for keyset pagination" },
          { name: "after", in: "query", schema: { type: "string" }, description: "Cursor after which to seek" },
          { name: "before", in: "query", schema: { type: "string" }, description: "Cursor before which to seek backwards" },
          { name: "direction", in: "query", schema: { type: "string", enum: ["next", "prev"] }, description: "Seek direction" }
        );
      }

      if (config?.search?.fields && config.search.fields.length > 0) {
        queryParams.push({
          name: "q",
          in: "query",
          schema: { type: "string" },
          description: `Full-text search query across: ${config.search.fields.join(", ")}`,
        });
      }

      if (config?.filter?.allow && config.filter.allow.length > 0) {
        for (const filterCol of config.filter.allow) {
          queryParams.push({
            name: String(filterCol),
            in: "query",
            schema: { type: "string" },
            description: `Filter by ${String(filterCol)}`,
          });
        }
      }

      paths[basePath] = paths[basePath] || {};
      paths[basePath].get = {
        summary: `List ${resourceName}`,
        tags: [tag],
        parameters: queryParams,
        responses: {
          200: {
            description: `Paginated list of ${resourceName}`,
            headers: rateLimitHeaders,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                    data: { type: "array", items: { $ref: `#/components/schemas/${modelName}` } },
                    meta: { $ref: "#/components/schemas/PaginationMeta" },
                  },
                  required: ["success", "data", "meta"],
                },
              },
            },
          },
          400: { description: "Bad request", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
          ...(hasRateLimit ? { 429: { description: "Rate limit exceeded", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } } } : {}),
        },
      };
    }

    // 2. POST /resource (create)
    if (allowedMethods.has("create")) {
      paths[basePath] = paths[basePath] || {};
      paths[basePath].post = {
        summary: `Create ${singularize(resourceName)}`,
        tags: [tag],
        parameters: idempotencyHeaderParam,
        requestBody: {
          required: true,
          content: {
            "application/json": {
              schema: { $ref: `#/components/schemas/${modelName}Create` },
            },
          },
        },
        responses: {
          201: {
            description: "Resource created successfully",
            headers: {
              ...rateLimitHeaders,
              ...(hasIdempotency ? { "Idempotent-Replayed": { schema: { type: "string" }, description: "Present if replayed from cache" } } : {}),
            },
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                    data: { $ref: `#/components/schemas/${modelName}` },
                  },
                  required: ["success", "data"],
                },
              },
            },
          },
          400: { description: "Validation error", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
          ...(hasIdempotency ? {
            409: { description: "Concurrent request in-flight lock", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
            422: { description: "Idempotency key payload mismatch", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
          } : {}),
          ...(hasRateLimit ? { 429: { description: "Rate limit exceeded", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } } } : {}),
        },
      };
    }

    // 3. GET /resource/{id} (detail)
    if (allowedMethods.has("detail")) {
      const itemPath = `${basePath}/{id}`;
      paths[itemPath] = paths[itemPath] || {};
      paths[itemPath].get = {
        summary: `Get ${singularize(resourceName)} by ID or slug`,
        tags: [tag],
        parameters: [
          { name: "id", in: "path", required: true, schema: { type: "string" }, description: "Primary key ID or unique slug" },
        ],
        responses: {
          200: {
            description: `Detail of ${singularize(resourceName)}`,
            headers: rateLimitHeaders,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                    data: { $ref: `#/components/schemas/${modelName}` },
                  },
                  required: ["success", "data"],
                },
              },
            },
          },
          404: { description: "Not found", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
        },
      };
    }

    // 4. PATCH /resource/{id} (update)
    if (allowedMethods.has("update")) {
      const itemPath = `${basePath}/{id}`;
      paths[itemPath] = paths[itemPath] || {};
      paths[itemPath].patch = {
        summary: `Update ${singularize(resourceName)}`,
        tags: [tag],
        parameters: [
          { name: "id", in: "path", required: true, schema: { type: "string" }, description: "Primary key ID" },
          ...idempotencyHeaderParam,
        ],
        requestBody: {
          required: true,
          content: {
            "application/json": {
              schema: { $ref: `#/components/schemas/${modelName}Update` },
            },
          },
        },
        responses: {
          200: {
            description: "Resource updated successfully",
            headers: rateLimitHeaders,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                    data: { $ref: `#/components/schemas/${modelName}` },
                  },
                  required: ["success", "data"],
                },
              },
            },
          },
          400: { description: "Validation error", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
          404: { description: "Not found", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
        },
      };
    }

    // 5. DELETE /resource/{id} (delete)
    if (allowedMethods.has("delete")) {
      const itemPath = `${basePath}/{id}`;
      paths[itemPath] = paths[itemPath] || {};
      paths[itemPath].delete = {
        summary: `Delete ${singularize(resourceName)}`,
        tags: [tag],
        parameters: [
          { name: "id", in: "path", required: true, schema: { type: "string" }, description: "Primary key ID" },
          ...idempotencyHeaderParam,
        ],
        responses: {
          200: {
            description: "Resource deleted successfully",
            headers: rateLimitHeaders,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                  },
                  required: ["success"],
                },
              },
            },
          },
          404: { description: "Not found", content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorEnvelope" } } } },
        },
      };
    }

    // 6. GET /resource/aggregate (analytics query)
    if (config?.aggregate && config.aggregate.enabled !== false && allowedMethods.has("aggregate")) {
      const aggPath = `${basePath}/aggregate`;
      paths[aggPath] = paths[aggPath] || {};
      paths[aggPath].get = {
        summary: `Query aggregations and analytics for ${resourceName}`,
        tags: [tag],
        parameters: [
          { name: "metrics", in: "query", schema: { type: "string" }, description: "Comma-separated metrics: count, sum:price, avg:total" },
          { name: "groupBy", in: "query", schema: { type: "string" }, description: "Comma-separated group-by columns" },
          { name: "dateInterval", in: "query", schema: { type: "string", enum: ["day", "week", "month", "year"] }, description: "Date bucketing interval" },
          { name: "dateColumn", in: "query", schema: { type: "string" }, description: "Date column used for date histogram" },
        ],
        responses: {
          200: {
            description: "Analytics aggregation results",
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                    data: { type: "array", items: { type: "object" } },
                  },
                  required: ["success", "data"],
                },
              },
            },
          },
        },
      };
    }

    // 7. PATCH /resource/batch-update
    if (allowedMethods.has("batch-update")) {
      const batchPath = `${basePath}/batch-update`;
      paths[batchPath] = paths[batchPath] || {};
      paths[batchPath].patch = {
        summary: `Batch update multiple ${resourceName}`,
        tags: [tag],
        parameters: idempotencyHeaderParam,
        requestBody: {
          required: true,
          content: {
            "application/json": {
              schema: {
                type: "array",
                items: {
                  type: "object",
                  properties: {
                    id: { type: "string" },
                  },
                  required: ["id"],
                },
              },
            },
          },
        },
        responses: {
          200: {
            description: "Batch update results",
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                    data: { type: "array", items: { $ref: `#/components/schemas/${modelName}` } },
                  },
                  required: ["success", "data"],
                },
              },
            },
          },
        },
      };
    }

    // 8. POST /resource/batch-delete
    if (allowedMethods.has("batch-delete")) {
      const batchDelPath = `${basePath}/batch-delete`;
      paths[batchDelPath] = paths[batchDelPath] || {};
      paths[batchDelPath].post = {
        summary: `Batch delete multiple ${resourceName}`,
        tags: [tag],
        parameters: idempotencyHeaderParam,
        requestBody: {
          required: true,
          content: {
            "application/json": {
              schema: {
                type: "object",
                properties: {
                  ids: { type: "array", items: { type: "string" } },
                },
                required: ["ids"],
              },
            },
          },
        },
        responses: {
          200: {
            description: "Batch delete result",
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    success: { type: "boolean", example: true },
                  },
                  required: ["success"],
                },
              },
            },
          },
        },
      };
    }
  }

  return {
    openapi: "3.1.0",
    info: {
      title,
      version,
      description,
    },
    paths,
    components: {
      schemas,
    },
  };
}
